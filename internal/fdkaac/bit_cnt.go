func FDKaacEncBitCountScalefactorDelta(delta int) int {
	index := delta + codeBookScfLav
	if index < 0 || index >= len(fdkaacEncHuffLtabScf) {
		panic("fdkaac: scalefactor delta out of range")
	}
	return int(fdkaacEncHuffLtabScf[index])
}
