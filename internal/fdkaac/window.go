package fdkaac

const (
	WindowShapeSine = 0
	WindowShapeKBD  = 1
	WindowShapeLOL  = 2
)

func FDKGetWindowSlope(length int, shape int) []FixpSPK {
	if length <= 0 {
		panic("fdkaac: window slope length not supported")
	}

	ld2Length := DfractBits - 1 - FixNormZD(FixpDBL(length)) - 1
	raster := 0
	switch length >> uint(ld2Length-2) {
	case 0x8:
		raster = 0
		ld2Length--
	case 0xf:
		raster = 1
	case 0xc:
		raster = 2
	default:
		raster = 0
	}

	shape &= 1
	if shape == WindowShapeKBD {
		ld2Length -= 4
	}

	if shape == WindowShapeSine {
		switch raster {
		case 0:
			switch ld2Length {
			case 5:
				return SineWindow128[:]
			case 8:
				return SineWindow1024[:]
			}
		case 1:
			switch ld2Length {
			case 5:
				return SineWindow120[:]
			case 8:
				return SineWindow960[:]
			}
		}
	} else {
		switch raster {
		case 0:
			switch ld2Length {
			case 1:
				return KBDWindow128[:]
			case 4:
				return KBDWindow1024[:]
			}
		case 1:
			switch ld2Length {
			case 1:
				return KBDWindow120[:]
			case 4:
				return KBDWindow960[:]
			}
		}
	}

	panic("fdkaac: window slope length not supported")
}

